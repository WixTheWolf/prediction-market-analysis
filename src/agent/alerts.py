"""Detect newly surfaced plays and arbitrage between consecutive scans.

The dashboard is pull-only; this module powers push notification. Each scan
is diffed against the previously published run, and only genuinely new
actionable plays or arbitrage candidates produce an alert body — repeat
appearances stay silent so the notification channel keeps signal value.
"""

from __future__ import annotations

from typing import Any, Iterable, Mapping, Optional

ATTRIBUTION_FOOTER = "---\n_Generated by [Claude Code](https://claude.ai/code)_"


def build_alert_body(
    current_opportunities: Iterable[Mapping[str, Any]],
    previous_opportunities: Iterable[Mapping[str, Any]],
    current_arbitrage: Iterable[Mapping[str, Any]],
    previous_arbitrage: Iterable[Mapping[str, Any]],
    *,
    dashboard_url: str,
    generated_at: str,
) -> Optional[str]:
    """Markdown alert for new plays/arbitrage, or None when nothing is new."""
    previous_plays = _play_keys(previous_opportunities)
    new_plays = [
        row
        for row in current_opportunities
        if str(row.get("action") or "PASS") != "PASS" and _play_key(row) not in previous_plays
    ]
    previous_arbs = {_arb_key(row) for row in previous_arbitrage}
    new_arbs = [row for row in current_arbitrage if _arb_key(row) not in previous_arbs]

    if not new_plays and not new_arbs:
        return None

    lines = [f"### New command-center signals · `{generated_at}`", ""]
    if new_plays:
        lines.extend(
            [
                f"**{len(new_plays)} new evidence-backed paper play(s):**",
                "",
                "| Side | Ticker | Market | Model | Edge | Confidence | Max loss |",
                "|---|---|---:|---:|---:|---:|---:|",
            ]
        )
        for row in new_plays[:10]:
            lines.append(
                f"| {str(row.get('side', '')).upper()} | `{row.get('ticker', '')}` | "
                f"{_pct(row.get('market_probability'))} | {_pct(row.get('model_probability'))} | "
                f"{_pct(row.get('edge'))} | {_pct(row.get('confidence'))} | "
                f"${float(row.get('maximum_loss_usd') or 0.0):,.2f} |"
            )
        lines.append("")
    if new_arbs:
        lines.extend([f"**{len(new_arbs)} new arbitrage candidate(s):**", ""])
        for row in new_arbs[:10]:
            lines.append(
                f"- {row.get('description', '')} → net {_pct(row.get('net_profit_after_buffer'))} after fee buffer"
            )
        lines.extend(
            ["", "> Cross-venue boxes are only real if both venues' resolution rules are identical — verify first."]
        )
    lines.extend(
        [
            "",
            f"[Open the dashboard]({dashboard_url}) · paper research only, no orders are placed.",
            "",
            ATTRIBUTION_FOOTER,
        ]
    )
    return "\n".join(lines) + "\n"


def _play_keys(opportunities: Iterable[Mapping[str, Any]]) -> set[tuple[str, str]]:
    return {_play_key(row) for row in opportunities if str(row.get("action") or "PASS") != "PASS"}


def _play_key(row: Mapping[str, Any]) -> tuple[str, str]:
    return (str(row.get("ticker") or ""), str(row.get("side") or "").lower())


def _arb_key(row: Mapping[str, Any]) -> tuple[str, ...]:
    legs = row.get("legs")
    tickers = []
    if isinstance(legs, list):
        tickers = sorted(f"{leg.get('ticker')}:{leg.get('side')}" for leg in legs if isinstance(leg, Mapping))
    return (str(row.get("kind") or ""), *tickers)


def _pct(value: Any) -> str:
    try:
        return f"{float(value):.1%}"
    except (TypeError, ValueError):
        return "—"
