from __future__ import annotations

from src.agent.alerts import build_alert_body

KWARGS = {
    "dashboard_url": "https://example.github.io/dash/",
    "generated_at": "2026-08-02T21:00:00Z",
}


def _play(ticker: str, side: str = "yes", action: str = "PAPER_BUY") -> dict:
    return {
        "ticker": ticker,
        "side": side,
        "action": action,
        "market_probability": 0.42,
        "model_probability": 0.55,
        "edge": 0.13,
        "confidence": 0.7,
        "maximum_loss_usd": 15.0,
    }


def _arb(ticker_a: str, ticker_b: str) -> dict:
    return {
        "kind": "cross_venue",
        "description": f"Buy YES on kalshi @ 0.40 + NO on polymarket @ 0.42 ({ticker_a}/{ticker_b})",
        "net_profit_after_buffer": 0.15,
        "legs": [
            {"ticker": ticker_a, "side": "yes"},
            {"ticker": ticker_b, "side": "no"},
        ],
    }


def test_new_play_and_arb_produce_alert() -> None:
    body = build_alert_body([_play("KX-NEW")], [], [_arb("KX-NEW", "pm-1")], [], **KWARGS)

    assert body is not None
    assert "KX-NEW" in body
    assert "1 new evidence-backed paper play(s)" in body
    assert "1 new arbitrage candidate(s)" in body
    assert "resolution rules" in body
    assert "_Generated by [Claude Code](https://claude.ai/code)_" in body


def test_repeat_signals_stay_silent() -> None:
    play = _play("KX-SAME")
    arb = _arb("KX-SAME", "pm-1")

    assert build_alert_body([play], [play], [arb], [arb], **KWARGS) is None


def test_pass_rows_never_alert() -> None:
    assert build_alert_body([_play("KX-P", action="PASS")], [], [], [], **KWARGS) is None


def test_side_change_counts_as_new() -> None:
    body = build_alert_body([_play("KX-FLIP", side="no")], [_play("KX-FLIP", side="yes")], [], [], **KWARGS)

    assert body is not None
    assert "NO" in body
